const TABLES: Record<string, Record<string, string>> = {
  reports: REPORTS,
  findings: FINDINGS,
  knowledge: KNOWLEDGE,
  common: COMMON,
};

/**
 * t 取文案：key 形如 "reports.title"。
 * 缺失的键原样返回（便于发现遗漏），不做抛错——UI 文案不该让页面挂掉。
 */
export function t(key: string): string {
  const dot = key.indexOf(".");
  if (dot < 0) return key;
  const table = TABLES[key.slice(0, dot)];
  if (!table) return key;
  const value = table[key.slice(dot + 1)];
  return value ?? key;
}

/**
 * ti 取文案并做 {var} 插值：ti("reports.genFailed", { msg: "…" })。
 */
export function ti(key: string, vars: Record<string, string | number>): string {
  let out = t(key);
  for (const [name, value] of Object.entries(vars)) {
    out = out.replaceAll(`{{${name}}}`, String(value));
  }
  return out;
}
